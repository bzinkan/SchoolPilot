import { teacherGuidePhases, teacherGuideTopics } from "../src/products/classpilot/guides/teacherGuideContent.js";
import { adminGuidePhases, adminGuideTopics } from "../src/products/classpilot/guides/adminGuideContent.js";

function renderTopic(topic) {
  const lines = [
    `### ${topic.title}`,
    "",
    `**Who can use this:** ${topic.role}`,
    "",
    topic.summary,
    "",
    ...topic.steps.flatMap((step, index) => [
      `${index + 1}. **${step.title}.** ${step.body}`,
    ]),
  ];

  for (const tip of topic.tips || []) {
    lines.push("", `> **Flight note:** ${tip}`);
  }
  if (topic.warning) {
    lines.push("", `> **Check before continuing:** ${topic.warning}`);
  }
  if (topic.route) {
    lines.push("", `[${topic.routeLabel || "Open this page"}](${topic.route})`);
  }
  return lines.join("\n");
}

export function renderGuideMarkdown({ title, description, phases, topics }) {
  const sections = phases.map((phase) => {
    const phaseTopics = topics.filter((topic) => topic.phase === phase);
    return [`## ${phase}`, "", ...phaseTopics.map(renderTopic)].join("\n\n");
  });

  return [
    `# ${title}`,
    "",
    "> Generated from the structured in-app ClassPilot guide source. Do not edit this file by hand.",
    "",
    description,
    "",
    `**Route:** ${title.includes("Teacher") ? "/classpilot/my-settings/guide" : "/classpilot/settings/guide"}`,
    "",
    ...sections,
    "",
  ].join("\n");
}

export const teacherGuideMarkdown = renderGuideMarkdown({
  title: "ClassPilot Teacher Guide",
  description: "Prepare, start, guide, monitor, and wrap up an exact-authority ClassPilot class.",
  phases: teacherGuidePhases,
  topics: teacherGuideTopics,
});

export const adminGuideMarkdown = renderGuideMarkdown({
  title: "ClassPilot Administrator Guide",
  description: "Launch, govern, operate, and support ClassPilot across the complete school admin experience.",
  phases: adminGuidePhases,
  topics: adminGuideTopics,
});

